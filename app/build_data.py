"""
Turns the summary CSVs in data/summary/ into app/data.js for the dashboard.

Run from the project folder after re-running the notebooks:
    python app/build_data.py

Why a .js file instead of reading the CSVs directly: the page then works by simply
opening index.html (browsers block reading local CSV files), and it can be copied
anywhere (GitHub Pages, a portfolio site) as one folder.
"""
import csv
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUMMARY = ROOT / "data" / "summary"
OUT = Path(__file__).resolve().parent / "data.js"

TOPICS = ["Food quality", "Rude service", "Long wait", "Wrong order",
          "Price / value", "Cleanliness", "Got sick", "Atmosphere"]


def read(name):
    with open(SUMMARY / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(value):
    """CSV values arrive as text; turn them into int or float."""
    x = float(value)
    return int(x) if x.is_integer() else x


headline = {row["metric"]: num(row["value"]) for row in read("eda_headline.csv")}

by_year = [{"year": num(r["review_year"]), "reviews": num(r["reviews"]),
            "pct": num(r["pct_negative"]), "margin": num(r["margin"]),
            "partial": num(r["is_partial_year"]) == 1}
           for r in read("eda_by_year.csv")]


def places(rows, label):
    return [{"name": label(r), "reviews": num(r["reviews"]), "restaurants": num(r["restaurants"]),
             "pct": num(r["pct_negative"]), "margin": num(r["margin"])} for r in rows]


cost = {r["topic"]: r for r in read("topics_star_cost.csv")}
topics = []
for r in read("topics_overall.csv"):
    c = cost[r["topic"]]
    topics.append({
        "topic": r["topic"],
        "shareNeg": num(r["share_of_negative"]), "sharePos": num(r["share_of_positive"]),
        "lift": num(r["times_more_in_negative"]),
        "mentions": num(c["reviews_mentioning"]),
        "starsWith": num(c["avg_stars_with"]), "starsWithout": num(c["avg_stars_without"]),
        "gapSimple": num(c["star_gap_simple"]), "gapFixed": num(c["star_gap_others_fixed"]),
    })

data = {
    "generated": date.today().isoformat(),
    "topics": TOPICS,
    "headline": {
        "reviews": headline["reviews"], "restaurants": headline["restaurants"],
        "pctNegative": headline["pct_negative"], "avgStars": headline["avg_stars"],
        "topicReviews": 296508,  # restaurant reviews kept by the text filter in notebook 02
    },
    "stars": [{"stars": num(r["stars"]), "pct": num(r["pct_reviews"])} for r in read("eda_stars.csv")],
    "byYear": by_year,
    "byState": places(read("eda_by_state.csv"), lambda r: r["state"]),
    "byCity": places(read("eda_by_city.csv"), lambda r: f'{r["city"]}, {r["state"]}'),
    "byCuisine": places(read("eda_by_cuisine.csv"), lambda r: r["category"]),
    "topicStats": topics,
    "topicsByYear": [{"year": num(r["review_year"]), "negReviews": num(r["negative_reviews"]),
                      "values": {t: num(r[t]) for t in TOPICS}}
                     for r in read("topics_by_year.csv") if r["partial"] == "0"],
    "topicsByCuisine": [{"cuisine": r["cuisine"], "negReviews": num(r["negative_reviews"]),
                         "values": {t: num(r[t]) for t in TOPICS}}
                        for r in read("topics_by_cuisine.csv")],
}

OUT.write_text("// Generated by app/build_data.py from data/summary/*.csv. Do not edit by hand.\n"
               "window.DASH_DATA = " + json.dumps(data, indent=1) + ";\n", encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.1f} KB)")
